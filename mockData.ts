export function calculatePressureIndex(m: PressureMetrics): number {
  const weighted =
    m.clutchConversion * 0.22 +
    m.overtimeDelta * 0.16 +
    m.lanRetention * 0.20 +
    m.eliminationImpact * 0.18 +
    m.commsComposure * 0.12 +
    m.mistakeRecovery * 0.12;
  return Math.round(weighted * 10) / 10;
}

export function calculateStackScore(s: StackMetrics): number {
  const stackLift = Math.max(0, Math.min(100, 50 + (s.fullStackWinRate - s.soloWinRate) * 2.2));
  const weighted =
    s.fullStackWinRate * 0.30 +
    s.tradeEfficiency * 0.25 +
    s.utilityAssistScore * 0.20 +
    s.roleFlexibility * 0.15 +
    stackLift * 0.10;
  return Math.round(weighted * 10) / 10;
}

